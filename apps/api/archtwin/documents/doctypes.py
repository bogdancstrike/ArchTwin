"""Document types the Docs tab can generate (registry).

Two modes:
  * `evidence` — deterministic Jinja2 templates over the snapshot. They are exhaustive: every system, container,
    endpoint, table and flow is documented (never a top-N), with Mermaid diagrams; every statement cites evidence [E#];
    regeneration yields a reviewable diff; hand-edited `archtwin:manual` sections survive.
  * `ai`       — full narrative documents (user guide, PRD, ARF, developer guide) drafted SECTION BY SECTION from an
    outline (`sections`): each section gets its own focused, cited evidence and its own model call, so the result is a
    complete document of its genre, not a summary. `per_feature` sections expand into one section per functional area.
Adding a document type = adding one `DocType` here (and, for evidence docs, its template; for AI docs, its outline).
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Literal

Mode = Literal["evidence", "ai"]
# Evidence families a section can draw on (see ai_writer.FAMILIES).
Focus = Literal["systems", "containers", "deploy", "endpoints", "features", "flows", "tables", "code", "externals", "adrs"]


@dataclass(frozen=True)
class Section:
    key: str
    title: str
    brief: str                                  # what this section must contain
    focus: tuple[str, ...]                      # evidence families given to the model
    query: str = ""                             # retrieval query for documentation / code passages
    passages: Literal["docs", "code", "any", "none"] = "docs"
    per_feature: bool = False                   # expands into one section per functional area (feature)


@dataclass(frozen=True)
class DocType:
    key: str
    title: str
    audience: str
    description: str
    mode: Mode
    template: str = ""              # evidence mode: Jinja2 template
    brief: str = ""                 # ai mode: genre, tone and purpose of the whole document
    retrieval: str = ""             # ai mode: default retrieval query
    sections: tuple[Section, ...] = field(default_factory=tuple)


