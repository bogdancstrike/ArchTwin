"""Document types the Docs tab can generate (registry).

Two modes:
  * `evidence` — deterministic Jinja2 templates over the snapshot: every statement cites evidence [E#]; regeneration yields a
    reviewable diff; hand-edited `archtwin:manual` sections survive.
  * `ai`       — narrative documents (user guide, PRD, ARF, developer guide) drafted by the model from the same cited facts
    plus retrieved documentation/code passages; citations are validated and the document is marked as a draft for review.
Adding a document type = adding one `DocType` here (and, for evidence docs, its template).
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

Mode = Literal["evidence", "ai"]


@dataclass(frozen=True)
class DocType:
    key: str
    title: str
    audience: str
    description: str
    mode: Mode
    template: str = ""              # evidence mode: Jinja2 template
    brief: str = ""                 # ai mode: what to write (sections, tone)
    retrieval: str = ""             # ai mode: query used to retrieve supporting passages



