"""Interchange exports: Mermaid (securityLevel strict) and Structurizr DSL, with escaping (XSS corpus tested)."""
from __future__ import annotations

import hashlib
import re
from typing import Any


def _mid(s: str) -> str:
    return "n_" + re.sub(r"[^A-Za-z0-9_]", "_", s)[:60] + "_" + hashlib.sha256(s.encode()).hexdigest()[:6]   # deterministic


def mermaid_text(s: str) -> str:
    # Mermaid labels: quote and entity-encode everything that could break out of the label or inject HTML
    s = s.replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("`", "&#96;").replace("|", "&#124;").replace("[", "&#91;").replace("]", "&#93;").replace("{", "&#123;").replace("}", "&#125;")
    return re.sub(r"[\r\n]+", " ", s)


def to_mermaid(view: dict[str, Any]) -> str:
    ids = {n["id"]: _mid(n["id"]) for n in view["nodes"]}
    lines = ["%%{init: {'securityLevel': 'strict'}}%%", "flowchart LR"]
    for n in view["nodes"]:
        label = mermaid_text(n["name"] + (f" — {n['technology']}" if n.get("technology") else ""))
        shape = ('(["', '"])') if n["kind"] == "person" else ('[("', '")]') if n.get("subtype") == "database" else ('["', '"]')
        lines.append(f"  {ids[n['id']]}{shape[0]}{label}{shape[1]}")
    for e in view["edges"]:
        if e["source"] in ids and e["target"] in ids:
            arrow = "-.->" if e["kind"] == "depends-on" or e.get("inferred_only") else "-->"
            lines.append(f'  {ids[e["source"]]} {arrow}|"{mermaid_text(e["label"])}"| {ids[e["target"]]}')
    for n in view["nodes"]:
        if n.get("focal"):
            lines.append(f"  style {ids[n['id']]} stroke:#eb6c36,stroke-width:2px")
    return "\n".join(lines) + "\n"


def dsl_str(s: str) -> str:
    return '"' + re.sub(r"[\r\n]+", " ", s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def to_structurizr(g: dict[str, Any], project_title: str) -> str:
    """Workspace with people, software systems (+ containers) and relationships from a snapshot graph."""
    nodes = g["nodes"]
    ident = {}

    def vid(k: str) -> str:
        if k not in ident:
            ident[k] = "e" + str(len(ident) + 1)
        return ident[k]

    contains = {}
    for e in g["edges"].values():
        if e["kind"] == "contains" and e["source"].startswith("system:"):
            contains.setdefault(e["source"], []).append(e["target"])
    out = [f"workspace {dsl_str(project_title)} {dsl_str('Generated by ArchTwin from evidence')} {{", "  model {"]
    for k, n in sorted(nodes.items()):
        if n["kind"] == "person":
            out.append(f"    {vid(k)} = person {dsl_str(n['name'])}")
        elif n["kind"] == "external-system":
            out.append(f"    {vid(k)} = softwareSystem {dsl_str(n['name'])} {dsl_str('External')} {{ tags \"External\" }}")
    for sk, members in sorted(contains.items()):
        out.append(f"    {vid(sk)} = softwareSystem {dsl_str(nodes[sk]['name'])} {{")
        for m in sorted(members):
            if m in nodes and nodes[m]["kind"] == "container":
                a = nodes[m]["attributes"]
                out.append(f"      {vid(m)} = container {dsl_str(nodes[m]['name'])} {dsl_str(a.get('description', ''))} {dsl_str(a.get('technology', ''))}")
        out.append("    }")
    for e in sorted(g["edges"].values(), key=lambda e: e["key"]):
        if e["kind"] in ("calls", "writes", "reads", "publishes", "consumes") and e["source"] in ident and e["target"] in ident:
            out.append(f"    {ident[e['source']]} -> {ident[e['target']]} {dsl_str(e['kind'])} {dsl_str(str(e['attributes'].get('protocol', '')))}")
    out += ["  }", "  views {", "    systemLandscape \"landscape\" { include * autoLayout lr }"]
    for sk in sorted(contains):
        out.append(f"    container {vid(sk)} {dsl_str('containers-' + nodes[sk]['name'])} {{ include * autoLayout lr }}")
    out += ["    theme default", "  }", "}"]
    return "\n".join(out) + "\n"
